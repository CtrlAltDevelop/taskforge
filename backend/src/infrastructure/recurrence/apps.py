from django.apps import AppConfig

from infrastructure.common.appsettings import AppSettings


class RecurrenceConfig(AppConfig):
    default_auto_field = "django.db.models.BigAutoField"
    name = "infrastructure.recurrence"
    label = "recurrence"
    verbose_name = "Recurring tasks"

    settings_spec = AppSettings(
        title="Recurring tasks",
        summary="Tasks that repeat on a schedule or after completion, generated by a clock.",
        requirements=(),
    )

    def ready(self) -> None:
        from infrastructure.recurrence import receivers

        receivers.connect()
